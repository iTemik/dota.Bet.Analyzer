#!/usr/bin/env node
/**
 * Version Management Script
 *
 * Usage:
 *   node scripts/version.js                    - Print current version
 *   node scripts/version.js major 2            - Set major version to 2
 *   node scripts/version.js build <number>     - Set build version
 */

const fs = require('fs');
const path = require('path');

const packageJsonPath = path.join(__dirname, '..', 'package.json');
const versionTsPath = path.join(__dirname, '..', 'frontend', 'src', 'version.ts');
const versionPyPath = path.join(__dirname, '..', 'backend', '__init__.py');

function getVersionFromPackageJson() {
    const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
    return pkg.version; // Format: "MAJOR.MINOR"
}

function setVersionInPackageJson(version) {
    const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
    pkg.version = version;
    fs.writeFileSync(packageJsonPath, JSON.stringify(pkg, null, 4) + '\n');
}

function getVersionFromFrontend() {
    const content = fs.readFileSync(versionTsPath, 'utf8');
    const match = content.match(/VERSION = ['"]([^'"]+)['"]/);
    return match ? match[1] : null;
}

function setVersionInFrontend(version) {
    const content = `// Frontend version - auto-generated by CI
export const VERSION = '${version}'
`;
    fs.writeFileSync(versionTsPath, content);
}

function getVersionFromBackend() {
    const content = fs.readFileSync(versionPyPath, 'utf8');
    const match = content.match(/__version__\s*=\s*['"]([^'"]+)['"]/);
    return match ? match[1] : null;
}

function setVersionInBackend(version) {
    let content = fs.readFileSync(versionPyPath, 'utf8');
    if (content.includes('__version__')) {
        content = content.replace(/__version__\s*=\s*['"][^'"]+['"]/, `__version__ = '${version}'`);
    } else {
        content = `__version__ = '${version}'\n` + content;
    }
    fs.writeFileSync(versionPyPath, content);
}

function getVersion() {
    const majorMinor = getVersionFromPackageJson();
    const build = process.env.BUILD_NUMBER || 'DEV';
    return `${majorMinor}.${build}`;
}

function incrementMinor(majorMinor) {
    const [major, minor = 0] = majorMinor.split('.').map(Number);
    return `${major}.${minor + 1}`;
}

function setMajorVersion(major) {
    setVersionInPackageJson(`${major}.0`);
    const fullVersion = `${major}.0.0`;
    setVersionInFrontend(fullVersion);
    setVersionInBackend(fullVersion);
    console.log(`Set version to ${fullVersion}`);
}

function setBuildVersion(buildNumber) {
    const majorMinor = getVersionFromPackageJson();
    const fullVersion = `${majorMinor}.${buildNumber}`;
    setVersionInFrontend(fullVersion);
    setVersionInBackend(fullVersion);
    console.log(`Set version to ${fullVersion}`);
}

function incrementMinorVersion() {
    const current = getVersionFromPackageJson();
    const next = incrementMinor(current);
    setVersionInPackageJson(next);
    const fullVersion = `${next}.0`;
    setVersionInFrontend(fullVersion);
    setVersionInBackend(fullVersion);
    console.log(`Incremented version to ${fullVersion}`);
    return fullVersion;
}

// CLI handling
const command = process.argv[2];
const arg = process.argv[3];

if (command === 'get') {
    console.log(getVersion());
} else if (command === 'get-full') {
    const majorMinor = getVersionFromPackageJson();
    const build = process.env.BUILD_NUMBER || 'DEV';
    console.log(`${majorMinor}.${build}`);
} else if (command === 'major') {
    setMajorVersion(arg);
} else if (command === 'build') {
    setBuildVersion(arg);
} else if (command === 'increment-minor') {
    incrementMinorVersion();
} else {
    console.log('Current version:', getVersion());
    console.log('Package.json:', getVersionFromPackageJson());
    console.log('Frontend:', getVersionFromFrontend());
    console.log('Backend:', getVersionFromBackend());
}
